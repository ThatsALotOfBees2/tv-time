#!/usr/bin/env python3
"""
Assembles the Raspberry Pi browser extension (pi/extension) from the shared sources, so the
Pi and the Android app always use the same start page, ad lists and blocking scripts.

    python3 pi/build-extension.py

Shared sources -> generated files in pi/extension:
    web/start/*                          -> start/*
    web/shield/youtube.js                -> youtube.js
    app/src/main/assets/inject.js        -> shield.js
    app/src/main/assets/adblock_hosts.txt-> rules/ads.json
    app/src/main/res/mipmap-xxxhdpi/...  -> icon.png
"""
import json
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXT = ROOT / "pi" / "extension"
HEADER = "/* GENERATED by pi/build-extension.py from {src} - edit that file instead. */\n"

# URL patterns blocked everywhere (in addition to whole ad domains).
URL_FILTERS = [
    "||youtube.com/api/stats/ads",
    "||youtube.com/pagead/",
    "||youtube.com/ptracking",
    "||youtube.com/get_midroll_",
    "||youtube.com/youtubei/v1/log_event",
    "/popunder",
    "popunder.js",
    "/pop.js",
    "/popads",
    "/pu.js",
    "/afu.php",
    "/push-notifications",
    "/onclick.js",
]


def copy_js(src: pathlib.Path, dst: pathlib.Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(HEADER.format(src=src.relative_to(ROOT).as_posix()) + src.read_text(encoding="utf-8"),
                   encoding="utf-8")


def read_hosts(path: pathlib.Path) -> list[str]:
    hosts = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        host = (parts[1] if len(parts) > 1 else parts[0]).lower()
        if re.fullmatch(r"[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+", host):
            hosts.append(host)
    return sorted(set(hosts))


def build_rules(hosts: list[str]) -> list[dict]:
    rules = []
    for i in range(0, len(hosts), 1000):
        rules.append({
            "id": len(rules) + 1,
            "priority": 1,
            "action": {"type": "block"},
            "condition": {"requestDomains": hosts[i:i + 1000], "excludedResourceTypes": ["main_frame"]},
        })
    for f in URL_FILTERS:
        rules.append({
            "id": len(rules) + 1,
            "priority": 1,
            "action": {"type": "block"},
            "condition": {"urlFilter": f, "excludedResourceTypes": ["main_frame"]},
        })
    return rules


def main() -> None:
    start_src = ROOT / "web" / "start"
    start_dst = EXT / "start"
    if start_dst.exists():
        shutil.rmtree(start_dst)
    start_dst.mkdir(parents=True)
    for f in sorted(start_src.iterdir()):
        if f.suffix == ".js":
            copy_js(f, start_dst / f.name)
        else:
            shutil.copy2(f, start_dst / f.name)

    copy_js(ROOT / "web" / "shield" / "youtube.js", EXT / "youtube.js")
    copy_js(ROOT / "app" / "src" / "main" / "assets" / "inject.js", EXT / "shield.js")

    hosts = read_hosts(ROOT / "app" / "src" / "main" / "assets" / "adblock_hosts.txt")
    (EXT / "rules").mkdir(exist_ok=True)
    (EXT / "rules" / "ads.json").write_text(json.dumps(build_rules(hosts), indent=1) + "\n", encoding="utf-8")

    shutil.copyfile(ROOT / "app" / "src" / "main" / "res" / "mipmap-xxxhdpi" / "ic_launcher.png", EXT / "icon.png")
    print(f"Built {EXT.relative_to(ROOT)} ({len(hosts)} blocked domains, {len(URL_FILTERS)} URL filters)")


if __name__ == "__main__":
    main()
